#include <iostream>
#include "Imos2D.cpp"

using namespace std;

int main() {
    // 4行5列のグリッドを管理する2次元いもす法オブジェクトを作成 (0-indexed)
    Imos2D imos(4, 5);

    // 行範囲 [1, 3)、列範囲 [2, 5) に 3 を加算
    // 対象セル: (1,2), (1,3), (1,4), (2,2), (2,3), (2,4)
    imos.add(1, 2, 3, 5, 3);

    // 行範囲 [2, 4)、列範囲 [1, 4) に -2 を加算
    // 対象セル: (2,1), (2,2), (2,3), (3,1), (3,2), (3,3)
    imos.add(2, 1, 4, 4, -2);

    // 累積和を計算して値を確定させる
    imos.build();

    // 結果の出力
    cout << "=== 2次元いもす法の結果 ===" << endl;
    for (int r = 0; r < 4; r++) {
        for (int c = 0; c < 5; c++) {
            cout << imos.get(r, c) << (c == 4 ? "" : " ");
        }
        cout << endl;
    }

    return 0;
}

/*
出力結果:
=== 2次元いもす法の結果 ===
0 0 0 0 0
0 0 3 3 3
0 -2 1 1 3
0 -2 -2 -2 0
*/
